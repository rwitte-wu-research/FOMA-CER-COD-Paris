main <- function() {
  t1   <- load_csv(file.path("output", "T1_results.csv"))
  loo  <- load_csv(file.path("output", "TF_loo.csv"))
  infl <- load_csv(file.path("output", "TF_influence.csv"), required = FALSE)
  t5   <- load_csv(file.path("output", "T5_results.csv"))

  doc <- paste(c(
    paste0("<!-- appendix_tables_A2_A4.md -- generated by ",
           "scripts/build_appendix_tables.R (M7 DEC); do not edit by hand -->"),
    "", "### Table A.2", "", build_a2(t1),
    "", "### Table A.3", "", build_a3(loo, infl),
    "", "### Table A.4", "", build_a4(t5), ""), collapse = "\n")

  dir.create("output", showWarnings = FALSE)
  con <- file(OUT_PATH, open = "wb")
  writeBin(charToRaw(enc2utf8(doc)), con)
  close(con)
  cat(doc, "\n")
  message(sprintf("[build_appendix_tables] ALL PINS PASS -- written to %s", OUT_PATH))
}

main()
